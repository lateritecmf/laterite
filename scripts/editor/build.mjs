// Builds the editor engines into crates/admin/assets/vendor and rewrites the
// attribution section of crates/admin/NOTICE from what actually went into them.
//
// Run from this directory after `npm ci`:  node build.mjs
//
// The output is committed; CI rebuilds it from the lockfile and fails on drift,
// so an upgrade is a deliberate commit that changes package.json, the lockfile,
// the bundles and the notice together. Nothing here depends on the clock, so
// the same inputs give the same bytes.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const outDir = join(root, 'crates', 'admin', 'assets', 'vendor');
const noticePath = join(root, 'crates', 'admin', 'NOTICE');

const bundles = [
  { entry: 'src/rich.js', out: 'richeditor', global: 'LateriteRich', title: 'Rich text (TipTap over ProseMirror)' },
  { entry: 'src/code.js', out: 'codeeditor', global: 'LateriteCode', title: 'Code and markdown (CodeMirror 6)' },
];

/** The npm package a bundled file came from, read from the nearest package.json. */
function packageOf(file) {
  let dir = dirname(resolve(here, file));
  while (dir.includes(`${sep}node_modules${sep}`)) {
    const manifest = join(dir, 'package.json');
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
      if (pkg.name && pkg.version) return { dir, pkg };
    }
    dir = dirname(dir);
  }
  return null;
}

/** The copyright line a package's LICENSE file opens with, if it ships one. */
function copyrightLine(dir) {
  const file = readdirSync(dir).find((f) => /^(LICENSE|LICENCE|COPYING)/i.test(f));
  if (!file) return null;
  const text = readFileSync(join(dir, file), 'utf8');
  const line = text.split('\n').map((l) => l.trim()).find((l) => /copyright/i.test(l));
  return line ? line.replace(/^#+\s*/, '') : null;
}

const sections = [];
for (const b of bundles) {
  const result = await build({
    entryPoints: [join(here, b.entry)],
    // Metafile paths are relative to this directory whatever the caller's cwd,
    // so the attribution below finds the same packages from the repository root.
    absWorkingDir: here,
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: b.global,
    outfile: join(outDir, `${b.out}.js`),
    target: 'es2022',
    legalComments: 'none',
    metafile: true,
    logLevel: 'warning',
    banner: { js: `/*! Laterite ${b.out}: built by scripts/editor from the packages listed in crates/admin/NOTICE. */` },
  });
  const packages = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const found = packageOf(input);
    if (!found) continue;
    const { dir, pkg } = found;
    const key = `${pkg.name}@${pkg.version}`;
    if (packages.has(key)) continue;
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url || '';
    packages.set(key, {
      name: pkg.name,
      version: pkg.version,
      license: pkg.license || '(unstated)',
      url: repo.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://'),
      copyright: copyrightLine(dir),
    });
  }
  const list = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
  sections.push({ ...b, list });
  const bytes = readFileSync(join(outDir, `${b.out}.js`)).length;
  console.log(`${b.out}.js: ${(bytes / 1024).toFixed(0)} KB, ${list.length} packages`);
}

// The attribution section, regenerated whole between its markers.
const BEGIN = 'Editor engines (generated by scripts/editor/build.mjs; do not edit by hand)';
const END = 'End of editor engines';
const lines = [BEGIN, '-'.repeat(BEGIN.length), ''];
lines.push(
  'The richeditor and codeeditor bundles in assets/vendor are built from the',
  'npm packages below, each under the licence stated. The MIT text is quoted',
  'once at the end; each package\'s own copyright line is given against it.',
  '',
);
const licences = new Set();
for (const s of sections) {
  lines.push(`${s.title}: ${s.out}.js`, '');
  for (const p of s.list) {
    licences.add(p.license);
    lines.push(`${p.name} ${p.version} (${p.license})`);
    if (p.url) lines.push(`    ${p.url}`);
    if (p.copyright) lines.push(`    ${p.copyright}`);
  }
  lines.push('');
}
const nonMit = [...licences].filter((l) => l !== 'MIT');
if (nonMit.length) {
  console.error(`A bundled package is not MIT: ${nonMit.join(', ')}. Quote its licence text here before committing.`);
  process.exit(1);
}
lines.push(
  'The MIT License',
  '',
  'Permission is hereby granted, free of charge, to any person obtaining a copy',
  'of this software and associated documentation files (the "Software"), to deal',
  'in the Software without restriction, including without limitation the rights',
  'to use, copy, modify, merge, publish, distribute, sublicense, and/or sell',
  'copies of the Software, and to permit persons to whom the Software is',
  'furnished to do so, subject to the following conditions:',
  '',
  'The above copyright notice and this permission notice shall be included in',
  'all copies or substantial portions of the Software.',
  '',
  'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR',
  'IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,',
  'FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE',
  'AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER',
  'LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,',
  'OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN',
  'THE SOFTWARE.',
  '',
  END,
);
const section = lines.join('\n') + '\n';
let notice = readFileSync(noticePath, 'utf8');
const start = notice.indexOf(BEGIN);
const stop = notice.indexOf(END);
if (start >= 0 && stop > start) {
  notice = notice.slice(0, start) + section + notice.slice(stop + END.length + 1);
} else {
  notice = notice.replace(/\n*$/, '\n\n\n') + section;
}
writeFileSync(noticePath, notice);
console.log('crates/admin/NOTICE: editor section regenerated');
